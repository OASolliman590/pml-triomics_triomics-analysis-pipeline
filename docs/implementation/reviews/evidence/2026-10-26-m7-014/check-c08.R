args <- commandArgs(trailingOnly=TRUE)
pkgload::load_all('.',quiet=TRUE)
root <- normalizePath(args[[1]],mustWork=TRUE)
stopifnot(!file.exists(file.path(root,'B','block-results.json')), !dir.exists(file.path(root,'B','handoffs')), !file.exists(file.path(root,'registries','run.json')))
allowed_b_files <- character()
stopifnot(length(list.files(root,pattern='^stage-handoff-provenance[.]json$',recursive=TRUE))==0L)
stopifnot(!file.exists(file.path(root,'D','handoff-manifest.json')))
x <- jsonlite::read_json(file.path(root,'C','integration-results.json'),simplifyVector=FALSE)
for(i in x$integrations){
 stopifnot(!is.null(i$score_endpoint_bundle),!is.null(i$clinical_score_request))
 ep <- file.path(root,i$score_endpoint_bundle$payload_file)
 ee <- file.path(root,i$score_endpoint_bundle$envelope_file)
 rp <- file.path(root,i$clinical_score_request$payload_file)
 re <- file.path(root,i$clinical_score_request$envelope_file)
 stopifnot(file.exists(ep),file.exists(rp),triomics_validate_envelope(ee),triomics_validate_envelope(re))
 allowed_b_files <- c(allowed_b_files,rp,re)
 r <- jsonlite::read_json(rp,simplifyVector=FALSE)
 stopifnot(identical(r$status,'scheduled'),identical(r$owner_stage,'B'),identical(r$model_execution,'not_started'),length(r$results)==0L)
 cat('ENDPOINT',ep,triomics_sha256(ep),'\nREQUEST',rp,triomics_sha256(rp),'\n')
}
stopifnot(setequal(list.files(file.path(root,'B'),recursive=TRUE,full.names=TRUE),allowed_b_files))
cat('READBACK PASS: endpoints and scheduled B request only; no B results, B handoff, C provenance or D handoff manifest.\n')
