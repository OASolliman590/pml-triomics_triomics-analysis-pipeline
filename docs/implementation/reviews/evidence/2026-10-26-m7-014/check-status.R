args <- commandArgs(trailingOnly=TRUE)
pkgload::load_all('.',quiet=TRUE)
root <- normalizePath(args[[1]],mustWork=TRUE)
x <- jsonlite::read_json(file.path(root,'D','evaluation-evidence.json'),simplifyVector=FALSE)
stopifnot(length(x$controls)==4L,all(vapply(x$controls,function(z)identical(z$status,'not_run'),logical(1))))
s <- jsonlite::read_json(file.path(root,'D','stage-status.json'),simplifyVector=FALSE)
stopifnot(identical(s$status,'partial'),identical(s$clinical_prediction$status,'not_started'))
b <- jsonlite::read_json(file.path(root,'registries','run.json'),simplifyVector=FALSE)
c <- jsonlite::read_json(file.path(root,'registries','run-C.json'),simplifyVector=FALSE)
stopifnot(identical(b$stage,'B'),identical(c$stage,'C'))
cat('STATUS PASS: four C07 controls not_run; C09 not_started; D aggregate partial; distinct B and C run records.\n')
